/// Per-warp telemetry of a [`WarpScheduler::run_kernel`] launch.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WarpRunTelemetry {
    /// Warp ordinal (0 = lanes `[0, width)`).
    pub warp_id: usize,
    /// First global lane id.
    pub lane_base: usize,
    /// Active lanes (launch tail warps are partial).
    pub active_lanes: u32,
    /// Warp cycles: 1 uniform, 2 divergent (§3 / ESM parity).
    pub cycles: u64,
    /// Whether any active lane reported `took_branch` (the ESM divergence
    /// signal — including a uniform all-lanes-taken branch).
    pub divergent: bool,
    /// Bit-packed taken-path mask (0 for uniform warps).
    pub taken_mask: u64,
    /// Bit-packed fallthrough mask (`active & !taken`; 0 for uniform warps).
    pub fallthrough_mask: u64,
    /// Max reconvergence-stack depth (1 divergent / 0 uniform for the
    /// single-branch ESM kernel model).
    pub reconvergence_depth_max: usize,
    /// Per-warp occupancy = active lanes / warp width (§3).
    pub occupancy: f64,
}

/// Whole-launch result of [`WarpScheduler::run_kernel`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct KernelRunResult {
    /// Per-lane outcomes in warp-major lane order (the ESM `results` array).
    pub results: Vec<LaneOutcome>,
    /// Total cycles = Σ per-warp `diverged ? 2 : 1` (ESM bit-exact).
    pub cycles: u64,
    /// Number of divergent warps (ESM `divergenceEvents`).
    pub divergence_events: u64,
    /// ESM occupancy formula: `lanes / ceil(lanes / width) / width`
    /// (evaluated in the same left-to-right associativity for f64
    /// bit-exactness).
    pub occupancy: f64,
    /// Per-warp telemetry (predicate masks, reconvergence, occupancy).
    pub warps: Vec<WarpRunTelemetry>,
    /// Total lane-switching events = Σ per-pass active lanes. Each active
    /// lane executes exactly one of the serialized paths, so this is
    /// divergence-invariant (divergence costs time, not lane events).
    pub switching_events: u64,
    /// Run-average dynamic power: `α·C_lane·(events / cycles)·V²·f`.
    pub dynamic_power_w: f64,
    /// Provenance of every number in this result.
    pub badge: ProvenanceBadge,
}

/// The SIMT warp scheduler — the ESM-parity execution surface.
#[derive(Debug, Clone, Copy)]
pub struct WarpScheduler {
    config: GpuConfig,
}

impl WarpScheduler {
    /// Validate and build a scheduler (fail-closed).
    ///
    /// # Errors
    /// [`GpuError`] from [`GpuConfig::validated`].
    pub fn new(config: GpuConfig) -> Result<Self, GpuError> {
        Ok(Self {
            config: config.validated()?,
        })
    }

    /// The validated configuration.
    #[must_use]
    pub const fn config(&self) -> &GpuConfig {
        &self.config
    }

    /// Run `kernel(lane, inputs[lane])` over `lanes_total` lanes in warps of
    /// the configured width — bit-exact with the ESM oracle
    /// `simulateWarpKernel(lanes, kernel, inputs)` at width 32: same warp
    /// partition, same `cycles += diverged ? 2 : 1`, same
    /// `divergenceEvents`, same `results` order, same occupancy formula.
    /// Additionally records the per-warp predicate masks, the
    /// reconvergence-stack depth and the power accounting the oracle does
    /// not expose (superset telemetry — never a divergence from it).
    ///
    /// # Errors
    /// [`GpuError::Dimensions`] for `lanes_total = 0` or an inputs buffer
    /// shorter than the launch.
    pub fn run_kernel(
        &self,
        lanes_total: usize,
        inputs: &[i64],
        kernel: impl Fn(usize, i64) -> LaneOutcome,
    ) -> Result<KernelRunResult, GpuError> {
        if lanes_total == 0 {
            return Err(GpuError::Dimensions(
                "lanes_total = 0 — an empty launch has no honest occupancy (the ESM formula would divide by zero)".into(),
            ));
        }
        if inputs.len() < lanes_total {
            return Err(GpuError::Dimensions(format!(
                "inputs: {} < lanes_total {lanes_total}",
                inputs.len()
            )));
        }
        let width = self.config.warp_width;
        let num_warps = lanes_total.div_ceil(width);
        let mut cycles = 0u64;
        let mut divergence_events = 0u64;
        let mut results = Vec::with_capacity(lanes_total);
        let mut warps = Vec::with_capacity(num_warps);
        let mut switching_events = 0u64;

        for warp_id in 0..num_warps {
            let lane_base = warp_id * width;
            let mut ex = WarpExecution::new(lane_base, width, lanes_total)?;
            let active = ex.active_lanes();
            let mut taken_mask = 0u64;
            // The single lockstep body pass: every active lane executes the
            // kernel once, in lane order (the ESM results order).
            for slot in 0..width {
                if ex.active_mask() & (1u64 << slot) == 0 {
                    break; // launch tail: all further slots inactive
                }
                let lane = lane_base + slot;
                let outcome = kernel(lane, inputs[lane]);
                if outcome.took_branch {
                    taken_mask |= 1u64 << slot;
                }
                results.push(outcome);
            }
            // ESM accounting: divergent ⇔ ANY active lane took the branch.
            let divergent = taken_mask != 0;
            cycles += 1; // the lockstep body pass
            switching_events += u64::from(active); // each active lane executes once
            let mut depth_max = 0usize;
            if divergent {
                // Serialize the second path (§3): +1 cycle, +1 event, one
                // reconvergence frame; each lane executes exactly one path.
                let taken = vec![false; width].into_boxed_slice();
                let mut taken_decisions = taken;
                for slot in 0..width {
                    taken_decisions[slot] = taken_mask & (1u64 << slot) != 0;
                }
                ex.branch(&taken_decisions)?;
                depth_max = ex.max_stack_depth();
                ex.reconverge();
                cycles += 1;
                divergence_events += 1;
            }
            // Per-warp occupancy = active lanes / warp width (§3).
            let occupancy = active as f64 / width as f64;
            warps.push(WarpRunTelemetry {
                warp_id,
                lane_base,
                active_lanes: active,
                cycles: if divergent { 2 } else { 1 },
                divergent,
                taken_mask: if divergent { taken_mask } else { 0 },
                fallthrough_mask: if divergent {
                    ex.active_mask() & !taken_mask
                } else {
                    0
                },
                reconvergence_depth_max: depth_max,
                occupancy,
            });
        }

        // ESM occupancy formula, same associativity:
        // `lanes / Math.ceil(lanes / 32) / 32` = (lanes / warps) / width.
        let occupancy = (lanes_total as f64 / num_warps as f64) / width as f64;

        // Run-average dynamic power: the lane-switching events spread over
        // the total cycles at the configured α·C·V²·f rate.
        let events_per_cycle = switching_events as f64 / cycles as f64;
        let cap = Farad::new(self.config.cap_per_lane_event_f * events_per_cycle);
        let power = crate::power::DynamicPowerModel::dynamic_power(
            self.config.activity,
            cap,
            Volt::new(self.config.vdd),
            Hertz::from_megahertz(self.config.clock_mhz),
        )
        .map_err(|e| GpuError::NonPhysicalInput(e.to_string()))?;

        Ok(KernelRunResult {
            results,
            cycles,
            divergence_events,
            occupancy,
            warps,
            switching_events,
            dynamic_power_w: power.value(),
            badge: GPU_BADGE,
        })
    }
}

/// `05` SIMT-throughput equation:
/// `ops_per_cycle = SM_count · cores_per_SM · ops_per_core_per_clock`.
#[must_use]
pub const fn ops_per_cycle(
    sm_count: usize,
    cores_per_sm: usize,
    ops_per_core_per_clock: usize,
) -> u128 {
    sm_count as u128 * cores_per_sm as u128 * ops_per_core_per_clock as u128
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The defaults validate.
    #[test]
    fn default_config_validates() {
        let c = GpuConfig::new().validated().expect("defaults valid");
        assert_eq!(c.warp_width, WARP_WIDTH_NVIDIA);
        assert_eq!(c.shared_banks, DEFAULT_SHARED_BANKS);
    }

    /// Uniform vs divergent: the exact §3 2× serialization penalty.
    #[test]
    fn divergent_warp_costs_exactly_twice_uniform() {
        let s = WarpScheduler::new(GpuConfig::new()).expect("valid");
        let inputs = vec![200i64; 32];
        let uniform = s
            .run_kernel(32, &inputs, |_, x| LaneOutcome::new(x, false))
            .expect("run");
        let divergent = s
            .run_kernel(32, &inputs, |_, x| LaneOutcome::new(x, true))
            .expect("run");
        assert_eq!(uniform.cycles, 1);
        assert_eq!(divergent.cycles, 2);
        assert_eq!(divergent.cycles, 2 * uniform.cycles);
    }

    /// Bank-conflict classic cases: stride-1 free, stride-width worst,
    /// broadcast free.
    #[test]
    fn bank_conflict_classic_cases() {
        let width = 32usize;
        let banks = 32usize;
        let stride1: Vec<usize> = (0..width).collect();
        let free = bank_conflicts(&stride1, u64::MAX, width, banks).expect("access");
        assert_eq!((free.serialized_cycles, free.extra_cycles), (1, 0));
        let stride_w: Vec<usize> = (0..width).map(|i| i * width).collect();
        let worst = bank_conflicts(&stride_w, u64::MAX, width, banks).expect("access");
        assert_eq!(worst.serialized_cycles, 32);
        assert_eq!(worst.extra_cycles, 31);
        assert_eq!(worst.conflict_banks, 1);
        let broadcast: Vec<usize> = vec![7; width];
        let b = bank_conflicts(&broadcast, u64::MAX, width, banks).expect("access");
        assert!(b.broadcast);
        assert_eq!(b.extra_cycles, 0);
    }

    /// Fail-closed config admission.
    #[test]
    fn config_admission_refuses_non_physical() {
        for (mut c, why) in [
            (GpuConfig::new(), "width"),
            (GpuConfig::new(), "banks"),
            (GpuConfig::new(), "clock"),
            (GpuConfig::new(), "vdd"),
        ] {
            match why {
                "width" => c.warp_width = 65,
                "banks" => c.shared_banks = 0,
                "clock" => c.clock_mhz = 0.0,
                _ => c.vdd = f64::NAN,
            }
            assert!(c.validated().is_err(), "{why} must be refused");
        }
    }
}
