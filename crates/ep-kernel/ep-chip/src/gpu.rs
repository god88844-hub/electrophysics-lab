// Vector ALU — per-lane SIMD ops executed in SIMT lockstep.
// ---------------------------------------------------------------------------

/// Vector-ALU opcodes of the declared per-lane datapath. All integer ops use
/// wrapping two's-complement semantics (SIMT ALUs do not trap on overflow).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum VectorAluOp {
    /// `a + b` (wrapping).
    Add,
    /// `a − b` (wrapping).
    Sub,
    /// `a · b` (wrapping).
    Mul,
    /// `a & b`.
    BitAnd,
    /// `a | b`.
    BitOr,
    /// `a ^ b`.
    BitXor,
    /// `a << (b & 63)` (shifting by the masked shift amount — no UB).
    Shl,
    /// Arithmetic `a >> (b & 63)` (sign-extending, masked shift amount).
    Shr,
}

impl VectorAluOp {
    /// Apply the op to one lane's operands (wrapping semantics).
    #[must_use]
    pub fn apply(self, a: i64, b: i64) -> i64 {
        match self {
            Self::Add => a.wrapping_add(b),
            Self::Sub => a.wrapping_sub(b),
            Self::Mul => a.wrapping_mul(b),
            Self::BitAnd => a & b,
            Self::BitOr => a | b,
            Self::BitXor => a ^ b,
            Self::Shl => a.wrapping_shl((b & 63) as u32),
            Self::Shr => a.wrapping_shr((b & 63) as u32),
        }
    }

    /// Assembly mnemonic (telemetry/honesty surfaces).
    #[must_use]
    pub const fn mnemonic(self) -> &'static str {
        match self {
            Self::Add => "vadd",
            Self::Sub => "vsub",
            Self::Mul => "vmul",
            Self::BitAnd => "vand",
            Self::BitOr => "vor",
            Self::BitXor => "vxor",
            Self::Shl => "vshl",
            Self::Shr => "vshr",
        }
    }
}

