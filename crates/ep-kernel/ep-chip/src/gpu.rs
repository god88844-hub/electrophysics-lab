/// SIMT warp-execution configuration (validated, fail-closed).
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct GpuConfig {
    /// Lanes per warp (`05 → warp_width`; 1..=[`MAX_WARP_WIDTH`] — the
    /// per-lane predicate masks are bit-packed into a `u64`).
    pub warp_width: usize,
    /// Core clock (MHz).
    pub clock_mhz: f64,
    /// Supply voltage (V).
    pub vdd: f64,
    /// Switching activity factor α (dimensionless).
    pub activity: f64,
    /// Per-lane switching capacitance per executed event (F).
    pub cap_per_lane_event_f: f64,
    /// Shared-memory bank count (classic default: the warp width).
    pub shared_banks: usize,
}

impl GpuConfig {
    /// The declared-default configuration (all values vault-anchored or
    /// explicitly declared model parameters — see the constants above).
    #[must_use]
    pub const fn new() -> Self {
        Self {
            warp_width: DEFAULT_WARP_WIDTH,
            clock_mhz: DEFAULT_CLOCK_MHZ,
            vdd: DEFAULT_VDD,
            activity: DEFAULT_ACTIVITY,
            cap_per_lane_event_f: CAP_PER_LANE_EVENT_F,
            shared_banks: DEFAULT_SHARED_BANKS,
        }
    }

    /// Fail-closed validation. Refuses (never silently clamps):
    /// warp widths outside `1..=[MAX_WARP_WIDTH]`, zero shared banks, and
    /// negative or non-finite clock/Vdd/α/capacitance (plus zero clock or
    /// capacitance, which are non-physical for a switching model).
    ///
    /// # Errors
    /// [`GpuError::Config`] / [`GpuError::NonPhysicalInput`] with the reason.
    pub fn validated(self) -> Result<Self, GpuError> {
        if self.warp_width == 0 || self.warp_width > MAX_WARP_WIDTH {
            return Err(GpuError::Config(format!(
                "warp_width = {} outside 1..={MAX_WARP_WIDTH} (the per-lane predicate masks are bit-packed into a u64; the 05-JSON vendor widths are 16/32/64)",
                self.warp_width
            )));
        }
        if self.shared_banks == 0 {
            return Err(GpuError::Config("shared_banks = 0 (need ≥ 1 bank)".into()));
        }
        for (name, v, allow_zero) in [
            ("clock_mhz", self.clock_mhz, false),
            ("vdd", self.vdd, false),
            ("activity", self.activity, true),
            ("cap_per_lane_event_f", self.cap_per_lane_event_f, false),
        ] {
            if !v.is_finite() || v < 0.0 || (!allow_zero && v == 0.0) {
                return Err(GpuError::NonPhysicalInput(format!("{name} = {v}")));
            }
        }
        Ok(self)
    }

    /// Instantaneous per-cycle dynamic power for a cycle in which
    /// `active_lanes` lanes switch: `P = α·(C_lane·n)·V²·f` (§3, scaled by
    /// the active-lane count — predicated-off lanes are clock-gated and
    /// contribute no switching event).
    ///
    /// # Errors
    /// [`GpuError::NonPhysicalInput`] for a non-finite or negative lane count.
    pub fn dynamic_power_w(&self, active_lanes: usize) -> Result<Watt, GpuError> {
        let n = active_lanes as f64;
        if !n.is_finite() || n < 0.0 {
            return Err(GpuError::NonPhysicalInput(format!(
                "active_lanes = {active_lanes}"
            )));
        }
        let cap = Farad::new(self.cap_per_lane_event_f * n);
        crate::power::DynamicPowerModel::dynamic_power(
            self.activity,
            cap,
            Volt::new(self.vdd),
            Hertz::from_megahertz(self.clock_mhz),
        )
        .map_err(|e| GpuError::NonPhysicalInput(e.to_string()))
    }
}

impl Default for GpuConfig {
    fn default() -> Self {
        Self::new()
    }
}

// ---------------------------------------------------------------------------
// Shared-memory bank-conflict accounting (classic model).
// ---------------------------------------------------------------------------

/// Result of one shared-memory access by a warp.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct SharedAccess {
    /// Cycles the access occupies = max lanes-per-bank (1 = conflict-free
    /// or broadcast).
    pub serialized_cycles: u64,
    /// Extra cycles beyond the conflict-free access (`serialized − 1`).
    pub extra_cycles: u64,
    /// Number of banks hit by ≥ 2 lanes (0 = conflict-free/broadcast).
    pub conflict_banks: usize,
    /// True when every active lane read the SAME address (hardware
    /// broadcasts it in one cycle even though the bank multiplicity is the
    /// lane count).
    pub broadcast: bool,
}

/// Account one shared-memory access: lanes `slot` (active per `mask`, bit
/// `slot` set, `slot < width`) read `addrs[slot]` from a memory with
/// `banks` banks. Cost = the max number of active lanes sharing one bank
/// (one bank serves one lane per cycle); a uniform same-address access is a
/// broadcast (one cycle). Inactive lanes never access.
///
/// # Errors
/// [`GpuError::Config`] for `banks = 0`; [`GpuError::Dimensions`] when
/// `addrs.len() < width`.
pub fn bank_conflicts(
    addrs: &[usize],
    mask: u64,
    width: usize,
    banks: usize,
) -> Result<SharedAccess, GpuError> {
    if banks == 0 {
        return Err(GpuError::Config("banks = 0 (need ≥ 1 bank)".into()));
    }
    if width == 0 || width > MAX_WARP_WIDTH {
        return Err(GpuError::Config(format!(
            "width = {width} outside 1..={MAX_WARP_WIDTH}"
        )));
    }
    if addrs.len() < width {
        return Err(GpuError::Dimensions(format!(
            "shared addresses: {} < warp width {width}",
            addrs.len()
        )));
    }
    let mut per_bank = vec![0usize; banks];
    let mut active = 0usize;
    let mut first_addr: Option<usize> = None;
    let mut all_same = true;
    for (slot, &a) in addrs.iter().enumerate().take(width) {
        if mask & (1u64 << slot) == 0 {
            continue; // predicated-off lane: no access, no conflict
        }
        active += 1;
        if let Some(first) = first_addr {
            all_same &= first == a;
        } else {
            first_addr = Some(a);
        }
        per_bank[a % banks] += 1;
    }
    if active == 0 {
        // Nobody accesses: zero-cost access.
        return Ok(SharedAccess {
            serialized_cycles: 0,
            extra_cycles: 0,
            conflict_banks: 0,
            broadcast: false,
        });
    }
    if all_same {
        return Ok(SharedAccess {
            serialized_cycles: 1,
            extra_cycles: 0,
            conflict_banks: 0,
            broadcast: true,
        });
    }
    let max_mult = per_bank.iter().copied().max().unwrap_or(0).max(1);
    let conflict_banks = per_bank.iter().filter(|m| **m > 1).count();
    Ok(SharedAccess {
        serialized_cycles: max_mult as u64,
        extra_cycles: (max_mult - 1) as u64,
        conflict_banks,
        broadcast: false,
    })
}

