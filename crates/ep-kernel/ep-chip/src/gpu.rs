/// Fail-closed GPU errors (admission discipline: refuse, never crash).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GpuError {
    /// Negative or non-finite clock/Vdd/α/capacitance, or a zero value where
    /// zero is non-physical.
    NonPhysicalInput(String),
    /// Structural config violations (warp width beyond the bit-packed mask,
    /// zero banks, …).
    Config(String),
    /// Dimension mismatches between the launch and the supplied buffers.
    Dimensions(String),
}

impl std::fmt::Display for GpuError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::NonPhysicalInput(what) => write!(f, "non-physical GPU input: {what}"),
            Self::Config(what) => write!(f, "GPU config refused: {what}"),
            Self::Dimensions(what) => write!(f, "GPU dimensions refused: {what}"),
        }
    }
}

impl std::error::Error for GpuError {}

