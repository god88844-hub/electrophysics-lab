// Warp execution datapath — active mask, reconvergence stack, per-instruction
// accounting for explicit kernel programs.
// ---------------------------------------------------------------------------

/// One reconvergence-stack frame: the two serialized path masks of a branch.
/// Bit `slot` set = the lane executes that path. The masks partition the
/// branch-time active mask; [`WarpExecution::reconverge`] restores their
/// union.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReconvergenceFrame {
    /// Lanes that took the branch.
    pub taken_mask: u64,
    /// Lanes that fell through (branch-time active minus taken).
    pub fallthrough_mask: u64,
}

/// Result of [`WarpExecution::branch`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BranchOutcome {
    /// No active lane took the branch — the fallthrough is the only path,
    /// nothing serializes, no stack frame.
    UniformNotTaken,
    /// At least one active lane took the branch — both paths serialize
    /// (§3: 2× the uniform cost), one frame pushed.
    Serialized {
        /// Lanes that execute the taken path first.
        taken_mask: u64,
        /// Lanes that execute the fallthrough path second.
        fallthrough_mask: u64,
    },
}

/// Per-warp execution datapath: bit-packed per-lane active predicate mask,
/// reconvergence stack and per-instruction cycle/event accounting.
///
/// Cycle model (declared): every executed instruction occupies ONE warp
/// cycle in SIMT lockstep, EXCEPT a taken branch which adds the second
/// serialized path cycle (§3 divergence penalty, ESM-parity accounting) and
/// a conflicted shared access which adds its bank-serialization extra
/// cycles.
#[derive(Debug, Clone)]
pub struct WarpExecution {
    lane_base: usize,
    width: usize,
    active_mask: u64,
    stack: Vec<ReconvergenceFrame>,
    cycles: u64,
    divergence_events: u64,
    max_stack_depth: usize,
    alu_instructions: u64,
    shared_extra_cycles: u64,
}

impl WarpExecution {
    /// A warp covering global lanes `[lane_base, lane_base + width)`; lanes
    /// ≥ `lanes_total` start predicated OFF (partial launch tail).
    ///
    /// # Errors
    /// [`GpuError::Config`] when `width` is outside `1..=[MAX_WARP_WIDTH]`.
    pub fn new(lane_base: usize, width: usize, lanes_total: usize) -> Result<Self, GpuError> {
        if width == 0 || width > MAX_WARP_WIDTH {
            return Err(GpuError::Config(format!(
                "warp width = {width} outside 1..={MAX_WARP_WIDTH}"
            )));
        }
        let mut active_mask = 0u64;
        for slot in 0..width {
            if lane_base + slot < lanes_total {
                active_mask |= 1u64 << slot;
            }
        }
        Ok(Self {
            lane_base,
            width,
            active_mask,
            stack: Vec::new(),
            cycles: 0,
            divergence_events: 0,
            max_stack_depth: 0,
            alu_instructions: 0,
            shared_extra_cycles: 0,
        })
    }

    /// First global lane id of this warp.
    #[must_use]
    pub const fn lane_base(&self) -> usize {
        self.lane_base
    }

    /// Bit-packed active predicate mask (bit `slot` = lane
    /// `lane_base + slot` active).
    #[must_use]
    pub const fn active_mask(&self) -> u64 {
        self.active_mask
    }

    /// Popcount of the active mask.
    #[must_use]
    pub fn active_lanes(&self) -> u32 {
        self.active_mask.count_ones()
    }

    /// Per-warp occupancy — §3: `active lanes / warp width` ∈ [0, 1].
    #[must_use]
    pub fn occupancy(&self) -> f64 {
        self.active_lanes() as f64 / self.width as f64
    }

    /// Cycles accounted so far (body instructions + serialized path cycles +
    /// shared-access extra cycles).
    #[must_use]
    pub const fn cycles(&self) -> u64 {
        self.cycles
    }

    /// Branch-serialization events so far.
    #[must_use]
    pub const fn divergence_events(&self) -> u64 {
        self.divergence_events
    }

    /// Maximum reconvergence-stack depth observed.
    #[must_use]
    pub const fn max_stack_depth(&self) -> usize {
        self.max_stack_depth
    }

    /// Vector-ALU instructions executed so far.
    #[must_use]
    pub const fn alu_instructions(&self) -> u64 {
        self.alu_instructions
    }

    /// Accumulated shared-access bank-conflict extra cycles.
    #[must_use]
    pub const fn shared_extra_cycles(&self) -> u64 {
        self.shared_extra_cycles
    }

    /// Current reconvergence-stack depth.
    #[must_use]
    pub fn stack_depth(&self) -> usize {
        self.stack.len()
    }

    /// Execute ONE vector-ALU instruction across the warp in SIMT lockstep:
    /// every ACTIVE slot computes `op(a[slot], b[slot])` into
    /// `regs[slot]`; predicated-off slots hold their register (clock-gated —
    /// no switching event). Occupies one warp cycle.
    ///
    /// # Errors
    /// [`GpuError::Dimensions`] when `regs`/`a`/`b` are shorter than the
    /// warp width.
    pub fn alu(
        &mut self,
        regs: &mut [i64],
        op: VectorAluOp,
        a: &[i64],
        b: &[i64],
    ) -> Result<(), GpuError> {
        if regs.len() < self.width || a.len() < self.width || b.len() < self.width {
            return Err(GpuError::Dimensions(format!(
                "alu operands: need ≥ {} slots, got regs {} / a {} / b {}",
                self.width,
                regs.len(),
                a.len(),
                b.len()
            )));
        }
        for slot in 0..self.width {
            if self.active_mask & (1u64 << slot) != 0 {
                regs[slot] = op.apply(a[slot], b[slot]);
            }
        }
        self.cycles += 1;
        self.alu_instructions += 1;
        Ok(())
    }

    /// Execute ONE branch instruction. `taken[slot]` is the per-lane branch
    /// decision (ignored for predicated-off slots). Any active lane taking
    /// the branch serializes both paths: pushes a [`ReconvergenceFrame`],
    /// adds the second path cycle and a divergence event
    /// (§3: 2× the uniform cost). A uniform not-taken branch costs nothing
    /// extra and leaves the stack untouched.
    ///
    /// After the paths' work, [`WarpExecution::reconverge`] pops the frame
    /// and restores the full branch-time active mask.
    ///
    /// # Errors
    /// [`GpuError::Dimensions`] when `taken` is shorter than the warp width.
    pub fn branch(&mut self, taken: &[bool]) -> Result<BranchOutcome, GpuError> {
        if taken.len() < self.width {
            return Err(GpuError::Dimensions(format!(
                "branch decisions: {} < warp width {}",
                taken.len(),
                self.width
            )));
        }
        let mut tmask = 0u64;
        for (slot, &t) in taken.iter().enumerate().take(self.width) {
            if self.active_mask & (1u64 << slot) != 0 && t {
                tmask |= 1u64 << slot;
            }
        }
        if tmask == 0 {
            return Ok(BranchOutcome::UniformNotTaken);
        }
        let branch_time_active = self.active_mask;
        let fmask = branch_time_active & !tmask;
        self.stack.push(ReconvergenceFrame {
            taken_mask: tmask,
            fallthrough_mask: fmask,
        });
        self.max_stack_depth = self.max_stack_depth.max(self.stack.len());
        // Execution continues on the taken path: the predicate mask narrows
        // to the taken lanes until reconvergence.
        self.active_mask = tmask;
        self.cycles += 1; // the second serialized path (ESM: diverged ? 2 : 1)
        self.divergence_events += 1;
        Ok(BranchOutcome::Serialized {
            taken_mask: tmask,
            fallthrough_mask: fmask,
        })
    }

    /// Reconverge: pop the top stack frame (if any) and restore the active
    /// mask to the union of its two path masks. Returns whether a frame was
    /// popped.
    pub fn reconverge(&mut self) -> bool {
        match self.stack.pop() {
            Some(frame) => {
                self.active_mask = frame.taken_mask | frame.fallthrough_mask;
                true
            }
            None => false,
        }
    }

    /// Execute ONE shared-memory access (`addrs[slot]` per slot, active
    /// lanes only) against the configured bank count. Bank-conflict extra
    /// cycles are added to the warp's cycle total.
    ///
    /// # Errors
    /// [`GpuError::Config`] for zero banks; [`GpuError::Dimensions`] for a
    /// short address buffer.
    pub fn shared_load(&mut self, addrs: &[usize], banks: usize) -> Result<SharedAccess, GpuError> {
        let access = bank_conflicts(addrs, self.active_mask, self.width, banks)?;
        self.cycles += access.extra_cycles;
        self.shared_extra_cycles += access.extra_cycles;
        Ok(access)
    }
}

