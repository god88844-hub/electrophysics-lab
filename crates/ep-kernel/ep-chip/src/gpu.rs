//! WP-4.2 SIMT GPU warp-execution engine
//! (`03_PHYSICS_MATH_FUNDAMENTALS.md` §3, `05_chip_architecture_benchmarks.json`
//! `simt_gpu`).
//!
//! Provenance: a declared architectural model —
//! [`ProvenanceBadge::SimulatedArchitecturalModel`] on every output surface
//! (Builder Rule 5). It is NOT an RTL model, a compiler-processed kernel
//! trace, or a silicon measurement. Warp geometry, the shared-memory bank
//! count and the whole-GPU envelopes below are anchored to the offline
//! reference vault (`05 → parameters.simt_gpu`,
//! `05 → valid_operating_envelope.simt_gpu`) — every constant is asserted
//! against the SHA-256-verified JSON payload by `tests/gpu_oracle.rs`
//! (Law 5: no invented constants).
//!
//! # Execution model (declared, §3-faithful)
//!
//! Lanes execute in lockstep warps. Each warp owns a per-lane **active
//! predicate mask** and a **reconvergence stack**: a branch on which active
//! lanes disagree (or which any active lane takes) serializes the two paths —
//! the warp pays one extra cycle (2× the uniform-warp cost, §3: "divergent
//! warp costs 2× the uniform warp, both paths serialized") and pushes a
//! [`ReconvergenceFrame`]; [`WarpExecution::reconverge`] pops the frame and
//! restores the full active mask. Uniform not-taken branches serialize
//! nothing (the fallthrough is the only path).
//!
//! The ESM-parity surface ([`WarpScheduler::run_kernel`]) reproduces
//! `packages/chip-engine/src/accelerators.mjs :: simulateWarpKernel`
//! **bit-exactly**: same warp partition (width 32), same per-warp
//! `cycles += diverged ? 2 : 1` accounting, same `divergenceEvents`, same
//! `results` order, same `occupancy = lanes / ceil(lanes / 32) / 32`
//! formula — asserted against a committed golden fixture captured from the
//! real oracle (`tests/data/gpu_parity_vectors.json`, generated by
//! `tests/data/gen_gpu_parity.mjs`) and re-validated live against Node when
//! Node is available (absent tool ⇒ loud SKIP, never a silent pass).
//!
//! Declared model granularity: one ESM `kernel(lane, input)` invocation is
//! ONE lockstep body cycle for the warp; the divergence penalty adds the
//! second serialized path cycle. Note the ESM convention (reproduced for
//! parity): a warp counts as divergent when ANY active lane reports
//! `tookBranch` — including a uniform all-lanes-taken branch — because the
//! oracle measures "the warp's program contains a taken branch", not mask
//! heterogeneity. The finer-grained [`WarpExecution`] datapath surface (ALU,
//! shared-memory, explicit branch) is provided for kernel programs that need
//! per-instruction accounting; it is the same declared model at
//! instruction granularity.
//!
//! # Shared memory
//!
//! [`bank_conflicts`] accounts the classic bank-conflict model: the shared
//! memory has `banks` (declared default: the warp width, 32) banks; an
//! access costs `max lanes-per-bank` cycles (extra cycles = that minus 1),
//! with the standard broadcast exception — all active lanes reading the SAME
//! address is conflict-free. Inactive lanes never access.
//!
//! # Power
//!
//! `P_dyn = α·C·V²·f` (§3) scaled by active lanes: a cycle in which `n`
//! lanes switch dissipates `α·(C_lane·n)·V²·f`
//! ([`GpuConfig::dynamic_power_w`]); a whole run averages to
//! `α·C_lane·(switching events / total cycles)·V²·f`
//! ([`KernelRunResult::dynamic_power_w`]). Divergence costs TIME (2× cycles),
//! not lane-switching events — each active lane executes exactly one of the
//! two serialized paths, so the event count is divergence-invariant; that is
//! the honest classic SIMT story and the tests assert both facts. The
//! scaling laws (∝f, ∝V², ∝active lanes) are verified exactly; the
//! capacitance is a declared model parameter of the ESM oracle's order, NOT
//! a measurement.

