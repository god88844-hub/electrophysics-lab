export const PHASE74_FORMAT='invention-lab/phase74-mvl-noise-crosstalk/1';
const finite=(n,label)=>{if(typeof n!=='number'||!Number.isFinite(n))throw Error(label+' must be finite');return n;};
const sorted=a=>a.every((x,i)=>i===0||a[i-1]<x);
const numTrace=(values,label)=>{
 if(!Array.isArray(values)||values.length<2||values.length>100000||values.some(x=>!Number.isFinite(x)))
  throw Error(label+' requires a bounded finite trace');
 return values;
};
// Each state MUST have independently observed rails under all three supply
// conditions, including dynamic peak excursions and capacitive coupling.
// These are voltage-window assessments, NOT calibrated foundry margins.
export function analyzeMvlNoiseMargins({rails,states,minimumSafeMarginV,
 rippleFractions=[-.1,0,.1],maxRailDroopV=0,maxCrosstalkV=0}={}){
 if(!rails||!Array.isArray(rails.rails)||rails.rails.length<2||rails.rails.length>16||
    !sorted(rails.rails)||rails.rails.some(x=>!Number.isFinite(x)))
  throw Error('Strictly ordered finite voltage rails required');
 finite(minimumSafeMarginV,'minimumSafeMarginV');
 if(minimumSafeMarginV<0||minimumSafeMarginV>=rails.spacingV/2)
  throw Error('Safety margin must fit within an adjacent state half-spacing');
 if(!Array.isArray(rippleFractions)||rippleFractions.length!==3||
    rippleFractions.some((x,i)=>Math.abs(x-[-.1,0,.1][i])>1e-12))
  throw Error('All -10%, nominal and +10% ripple conditions required');
 finite(maxRailDroopV,'maxRailDroopV');finite(maxCrosstalkV,'maxCrosstalkV');
 if(maxRailDroopV<0||maxCrosstalkV<0)throw Error('Negative disturbance envelope');
 if(!Array.isArray(states)||states.length!==rails.rails.length*3)
  return {format:PHASE74_FORMAT,status:'INSUFFICIENT_MODEL_DATA',reason:'required-ripple-state-measurements-missing',
   marginsV:null,physicalQualification:false};
 const seen=new Set(),byState=Array.from({length:rails.rails.length},()=>[]);
 for(const s of states){
  if(!Number.isInteger(s?.state)||s.state<0||s.state>=rails.rails.length||
     !rippleFractions.some(r=>Math.abs(s.rippleFraction-r)<=1e-12))
   throw Error('Invalid state or supply corner');
  const key=s.state+'/'+s.rippleFraction.toFixed(3);
  if(seen.has(key))throw Error('Duplicate state/ripple sample');
  seen.add(key);
  const dc=numTrace(s.dcOutputV,'DC output');
  const transient=numTrace(s.transientOutputV,'Transient output');
  const all=[...dc,...transient];
  const observedMin=Math.min(...all),observedMax=Math.max(...all);
  byState[s.state].push({rippleFraction:s.rippleFraction,observedMin,observedMax,
   eyeOpeningV:finite(s.eyeOpeningV,'eyeOpeningV')});
 }
 const midpoint=rails.rails.slice(1).map((x,i)=>(x+rails.rails[i])/2);
 const marginsV=byState.map((group,i)=>{
  if(group.length!==3)throw Error('Missing state ripple measurement');
  let safe=Infinity;
  for(const s of group){
   const min=s.observedMin-maxRailDroopV-maxCrosstalkV;
   const max=s.observedMax+maxRailDroopV+maxCrosstalkV;
   if(i>0)safe=Math.min(safe,min-midpoint[i-1]);
   if(i<byState.length-1)safe=Math.min(safe,midpoint[i]-max);
   if(!Number.isFinite(s.eyeOpeningV)||s.eyeOpeningV<0)throw Error('Invalid eye opening');
   safe=Math.min(safe,s.eyeOpeningV/2);
  }
  return +safe.toFixed(12);
 });
 const unsafe=marginsV.map((n,i)=>n<minimumSafeMarginV?i:null).filter(x=>x!==null);
 const names=marginsV.map((x,i)=>({state:i,key:rails.base===4?['NM_L','NM_1','NM_2','NM_H'][i]:i===0?'NM_L':i===marginsV.length-1?'NM_H':'NM_'+i,marginV:x}));
 return {format:PHASE74_FORMAT,status:unsafe.length?'VIRTUAL_FAIL':'MODEL_WINDOW_PASS',
  marginByState:names,unsafeStates:unsafe,
  conditions:'dc-and-transient-at-three-supply-ripple-corners',
  maxRailDroopV,maxCrosstalkV,minimumSafeMarginV,
  foundryCalibrated:false,physicalQualification:false};
}
// Runs actual executable. Missing ngspice is NOT simulation success.
// Provided decks must be generated by an audited caller; SPICE includes
// and arbitrary device subcircuits are not trusted input.
export async function runMvlNgspiceMeasurements({exe,dcDeck,transientDeck,
 dcVectorCount=1,transientVectorCount=1,soaNetlist=null}={}){
 if(typeof exe!=='string'||!exe||![dcDeck,transientDeck].every(
   x=>typeof x==='string'&&x.length>10&&x.length<2_000_000))
  return {status:'INSUFFICIENT_MODEL_DATA',reason:'ngspice-or-deck-unavailable'};
 // A foundry .lib, model .include, or transistor subcircuit in the deck
 // MUST enter the SOA preflight before a native process is even spawned.
 // Ohmic-only reference tests are still allowed but never PDK-calibrated.
 const decks=[dcDeck,transientDeck];
 const needsSOA=decks.some(deck=>/^\s*(?:\.lib\b|\.include\b|x[A-Za-z0-9_]+\s)/mi.test(deck));
 if(needsSOA){
  if(!soaNetlist||!soaNetlist.profile||!Array.isArray(soaNetlist.devices))
   return {format:PHASE74_FORMAT,status:'SOA_INSUFFICIENT_NODE_BOUNDS',
    reason:'device-terminal-SOA-preflight-required-before-ngspice',
    verifiedPdk:false,physicalQualification:false};
  // Enforce one-to-one binding of declared terminal extrema to transistor
  // instances. Do not let a caller pass a safe checker for a different deck.
  const instances=new Map();
  for(const deck of decks){
   for(const line of deck.split(/\r?\n/)){
    if(!/^\s*x[A-Za-z0-9_]+\s/i.test(line))continue;
    const tokens=line.trim().split(/\s+/),instance=tokens[0].toLowerCase();
    const declared=tokens.slice(1).find(t=>Object.hasOwn(MOS_SOA_LIMITS,t));
    if(!declared||instances.has(instance)&&instances.get(instance)!==declared)
     return {format:PHASE74_FORMAT,status:'SOA_INSUFFICIENT_NODE_BOUNDS',
      reason:'unrecognized-or-reused-transistor-device-in-spice-deck',
      verifiedPdk:false,physicalQualification:false};
    instances.set(instance,declared);
   }
  }
  if(instances.size<1||soaNetlist.devices.length!==instances.size||
     soaNetlist.devices.some(d=>typeof d?.instance!=='string'||
      instances.get(d.instance.toLowerCase())!==d.model))
   return {format:PHASE74_FORMAT,status:'SOA_INSUFFICIENT_NODE_BOUNDS',
    reason:'device-instance-to-terminal-sample-inventory-does-not-match-spice-deck',
    verifiedPdk:false,physicalQualification:false};
  const checked=requireSafeNetlistSOA(soaNetlist);
  if(checked.status!=='SOA_MODEL_RANGE_SCREEN_PASS')
   return {format:PHASE74_FORMAT,status:checked.status,
    reason:'native-ngspice-blocked-by-soa',
    soa:checked,verifiedPdk:false,physicalQualification:false};
  for(const [kind,deck] of [['dc',dcDeck],['transient',transientDeck]]){
   const originalBounds=verifyDeckTerminalSOA({
    deck,profile:soaNetlist.profile,devices:soaNetlist.devices});
   if(originalBounds.status!=='SOA_MODEL_RANGE_SCREEN_PASS')
    return {format:PHASE74_FORMAT,status:originalBounds.status,
     reason:kind+'-source-derived-terminal-soa-rejected',
     sourceBoundSOA:originalBounds,
     verifiedPdk:false,physicalQualification:false};
  }
 }
 const results=[];
 for(const [kind,deck,expectedVectors] of [['dc',dcDeck,dcVectorCount],['transient',transientDeck,transientVectorCount]]){
  if(!Number.isInteger(expectedVectors)||expectedVectors<1||expectedVectors>16)
   throw Error('Invalid SPICE vector count');
  const raw=await runNgspice({exe,deck,timeoutMs:60_000});
  const fail=detectNgspiceFailure(raw);
  if(fail)return {status:'INSUFFICIENT_MODEL_DATA',reason:kind+'-ngspice-failed',detail:fail};
  const file=Object.entries(raw.artifacts||{}).find(([name])=>name===kind+'.txt')?.[1];
  if(!file)return {status:'INSUFFICIENT_MODEL_DATA',reason:kind+'-sweep-data-missing'};
  try{results.push({kind,rows:parseWrdata(file,expectedVectors).series});}
  catch(e){return {status:'INSUFFICIENT_MODEL_DATA',reason:kind+'-sweep-malformed',detail:e.message};}
 }
 return {format:PHASE74_FORMAT,status:'MEASURED_SPICE_TRACES',results,
  verifiedPdk:false,physicalQualification:false};
}
